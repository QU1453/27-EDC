#ifndef __APP_IMU_H
#define __APP_IMU_H

/* =====================================================================
 * app_imu.h —— 姿态传感器任务（App 层）
 *
 * 文件作用：
 *   把 BSP 层的 YbImu 驱动跑起来：初始化 I2C1（PB7=SDA/PA15=SCL）轮询，
 *   并把欧拉角/角速度刷到板载 LCD 上，方便上电直接看现象。
 *   需要姿态数据的模块（如航向闭环）直接调 BSP_IMU_GetData()，不必经过这里。
 *
 * 命名对照：
 *   App     = 应用层（任务调度）
 *   Task    = 周期任务，非阻塞，主循环里调
 * ===================================================================== */

/* 作用：初始化姿态传感器（I2C 在线探测）并画静态界面 */
void App_IMU_Init(void);

/* 作用：周期任务，主循环里调用。内部每 250 ms 刷一次屏，
 * 屏刷用整行批量发，约 5 ms，不会长时间挡住主循环 */
void App_IMU_Task(void);

#endif
